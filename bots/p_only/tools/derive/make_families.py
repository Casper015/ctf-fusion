"""Derive the feature-family carriers from the P-only carriers (docs/FEATURE_FAMILIES.md).

    python bots/p_only/tools/derive/make_families.py

Writes, without touching the carriers they come from (every existing variant stays byte-identical):

  bots/p_only/include/ponly_p3.hpp   ponly.hpp for policy family p3: PolicyFeaturesP3 / PolicyModelP3, one combat
                                     summary per built state (inference/combat.hpp), rules from INIT
  bots/p_only/bots/v12_ponly_f.hpp   v12_ponly.hpp with family selection and the bounded V route
  bots/p_only/bots/c08_ponly_f.hpp   c08_ponly.hpp likewise

A variant wrapper selects the families and the model set:

    #define PONLY_POLICY_FAMILY 3                     // 2 (default) or 3
    #define PONLY_VALUE_FAMILY 3                      // 2 (default) or 3
    #define MOD_FUSION_V 1
    #include "models_pxxl_v3_4xl/registry.hpp"        // any exported set; it must come first
    #include "v12_ponly_f.hpp"

The registry's ModelSet types must be the selected families (static_assert), so a wrapper cannot pair p3
code with p2 weights or the reverse. Without a pre-included registry the tier ladder of the carrier applies.

Route A, direct V with a bound: PONLY_V_MAX_CALLS caps network V evaluations per turn and PONLY_V_DEADLINE_MS
stops them once that many milliseconds of the turn have passed (both off by default). A decision path whose V
was cut takes the same path's choice without V (the carrier already computes it: answerH, or the search's own
choice for C08's beam re-ranking), so no decision mixes candidates scored with and without V. Under
PONLY_STATS one more stderr line reports the bound: VBUDGET max_calls .. deadline_ms .. skipped_calls ..
fallback_decisions ..

The search experiment of task T0018 (search_experiment.py: action portfolio, per-branch ply-2 predictions,
their counters) is applied on top, every part off by default.

Every replaced text is matched exactly with its expected count, so a changed source is refused, never
spliced at the wrong place. PONLY_DERIVE_DIR redirects the output (tests re-derive and compare).
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import search_experiment  # noqa: E402  (task T0018: the search experiment's settings, off by default)

REPO = Path(__file__).resolve().parents[4]
OUT = Path(os.environ["PONLY_DERIVE_DIR"]) if os.environ.get("PONLY_DERIVE_DIR") else None


def apply(text: str, edits, name: str) -> str:
    for old, new, count in edits:
        n = text.count(old)
        if n != count:
            sys.exit(f"{name}: expected {count} occurrence(s) of {old[:70]!r}, found {n}")
        text = text.replace(old, new)
    return text


def write(rel: str, text: str) -> None:
    path = OUT / Path(rel).name if OUT else REPO / rel
    path.write_text(text, encoding="utf-8")


# ---------------------------------------------------------------- ponly_p3.hpp
ponly = (REPO / "bots/p_only/include/ponly.hpp").read_text(encoding="utf-8")
P3_HEADER = """// Generated by bots/p_only/tools/derive/make_families.py from ponly.hpp. Do not edit.
// Policy family p3: the same View with PolicyFeaturesP3 and PolicyModelP3
// (inference/policy_p3.hpp). One combat summary per built state serves every
// encoded team; `rules` (damage and hit points from INIT) must be set by the
// carrier before the first build. The p2 part of every input is the legacy
// encoder's, bit for bit.
"""
ponly_p3 = P3_HEADER + apply(ponly, [
    ("#ifndef PONLY_HPP\n#define PONLY_HPP\n", "#ifndef PONLY_P3_HPP\n#define PONLY_P3_HPP\n", 1),
    ('#include "policy.hpp"\n', '#include "policy.hpp"\n#include "policy_p3.hpp"\n', 1),
    ("    Counters* counters = nullptr;\n", "    Counters* counters = nullptr;\n    fusion::Rules rules{};  // engine damage and hit points (INIT); set by the carrier\n", 1),
    ("               const fusion::PolicyModel* model, const std::vector<char>* want = nullptr) {",
     "               const fusion::PolicyModelP3* model, const std::vector<char>* want = nullptr) {", 1),
    ("        fusion::makeView(b, s_, parent, v_);\n", "        fusion::makeView(b, s_, parent, v_);\n        fusion::summarize(b, rules, s_, v_, cs_);\n", 1),
    ("            fusion::encodePolicy(b, s_, v_, t, feat_[t]);", "            fusion::encodePolicyP3(b, s_, v_, cs_, t, feat_[t]);", 1),
    ("    const fusion::PolicyModel* model_ = nullptr;", "    const fusion::PolicyModelP3* model_ = nullptr;\n    fusion::CombatSummary cs_;", 1),
    ("    std::vector<fusion::PolicyFeatures> feat_;", "    std::vector<fusion::PolicyFeaturesP3> feat_;", 1),
    ("#endif  // PONLY_HPP", "#endif  // PONLY_P3_HPP", 1),
], "ponly.hpp")
write("bots/p_only/include/ponly_p3.hpp", ponly_p3)

# ---------------------------------------------------------------- carriers
FAMILY_INCLUDES = """#ifndef PONLY_POLICY_FAMILY
#define PONLY_POLICY_FAMILY 2
#endif
#ifndef PONLY_VALUE_FAMILY
#define PONLY_VALUE_FAMILY 2
#endif
#ifndef PONLY_V_MAX_CALLS
#define PONLY_V_MAX_CALLS 1000000000
#endif
#ifndef PONLY_V_DEADLINE_MS
#define PONLY_V_DEADLINE_MS 1e9
#endif
#include "combat.hpp"
#if PONLY_POLICY_FAMILY == 3
#include "ponly_p3.hpp"
#define PONLY_RULES_TO(v) ((v).rules = rules)
#else
#include "ponly.hpp"
#define PONLY_RULES_TO(v) ((void)0)
#endif
#if PONLY_VALUE_FAMILY == 3
#include "value_v3.hpp"
#endif
"""
REGISTRY_FIRST = """#if defined(FUSION_MODELS_REGISTRY_HPP)
// The variant included its model set's registry first (any exported set).
#elif defined(FUSION_TIER_M)"""
FAMILY_TYPES = """
// The registry's model types must be the selected families.
#include <type_traits>
#if PONLY_POLICY_FAMILY == 3
static_assert(std::is_same_v<decltype(fusion::models::ModelSet::policy), const fusion::PolicyModelP3*>, "model set is not policy family p3");
#else
static_assert(std::is_same_v<decltype(fusion::models::ModelSet::policy), const fusion::PolicyModel*>, "model set is not policy family p2");
#endif
#if PONLY_VALUE_FAMILY == 3
static_assert(std::is_same_v<decltype(fusion::models::ModelSet::value), const fusion::ValueModelV3*>, "model set is not value family v3");
#else
static_assert(std::is_same_v<decltype(fusion::models::ModelSet::value), const fusion::ValueModel*>, "model set is not value family v2");
#endif
"""
V_ENCODE_OLD = """            fusion::ValueFeatures vf;
            fusion::encodeValue(board, st, vw, {me}, vf);
            return fusion::value(*model->value, vf);"""
V_ENCODE_NEW = """#if PONLY_VALUE_FAMILY == 3
            fusion::ValueFeaturesV3 vf;
            fusion::summarize(board, rules, st, vw, vcs);
            fusion::encodeValueV3(board, st, vw, vcs, {me}, vf);
#else
            fusion::ValueFeatures vf;
            fusion::encodeValue(board, st, vw, {me}, vf);
#endif
            return fusion::value(*model->value, vf);"""
SESSION_INIT_OLD = "            if (!initialized) { board.init(makeStatic(g)); initialized = true; }"
BUDGET_MEMBERS = """    // Route A bound (make_families.py): network V calls this turn, the turn's start, and whether a V call was
    // skipped in this turn (the affected decision path then takes its choice without V).
    long long vTurnCalls = 0, vSkipped = 0, vFallbacks = 0;
    bool vCut = false;
    chrono::steady_clock::time_point vTurnStart{};
    void vTurnBegin() { vTurnCalls = 0; vCut = false; vTurnStart = chrono::steady_clock::now(); }
    bool vAllowed() {
        const double ms = chrono::duration<double, std::milli>(chrono::steady_clock::now() - vTurnStart).count();
        if (vCut || vTurnCalls >= PONLY_V_MAX_CALLS || ms > PONLY_V_DEADLINE_MS) { vCut = true; vSkipped++; return false; }
        vTurnCalls++;
        return true;
    }
    void vBudgetReport(const Game& g) const {
#if PONLY_STATS
        if (g.turn == g.turns) std::cerr << "VBUDGET max_calls " << PONLY_V_MAX_CALLS << " deadline_ms " << PONLY_V_DEADLINE_MS
                                         << " skipped_calls " << vSkipped << " fallback_decisions " << vFallbacks << std::endl;
#else
        (void)g;
#endif
    }
"""

carrier_header = lambda name, src: f"""// Generated by bots/p_only/tools/derive/make_families.py from {src}. Do not edit.
// Family-aware {name}: PONLY_POLICY_FAMILY (2 or 3) and PONLY_VALUE_FAMILY (2 or 3) choose the
// encoders; a variant may include any model set's registry before this header; PONLY_V_MAX_CALLS and
// PONLY_V_DEADLINE_MS bound network V per turn (a cut decision path takes its choice without V).
"""

v12 = (REPO / "bots/p_only/bots/v12_ponly.hpp").read_text(encoding="utf-8")
v12f = carrier_header("v12 P-only carrier", "v12_ponly.hpp") + apply(v12, [
    ('#include "ponly.hpp"\n', FAMILY_INCLUDES, 1),
    ("#if defined(FUSION_TIER_M)", REGISTRY_FIRST, 1),
    ('#include "models/registry.hpp"\n#endif\n', '#include "models/registry.hpp"\n#endif\n' + FAMILY_TYPES, 1),
    ("        const fusion::PolicyModel* policy() const { return model ? model->policy : nullptr; }",
     "        fusion::Rules rules{};\n        mutable fusion::CombatSummary vcs;  // value v3: one summary per evaluated state, buffers reused\n"
     "        decltype(fusion::models::ModelSet::policy) policy() const { return model ? model->policy : nullptr; }", 1),
    (SESSION_INIT_OLD, "            if (!initialized) { board.init(makeStatic(g)); rules = fusion::rulesOf(makeStatic(g)); PONLY_RULES_TO(view); initialized = true; }", 1),
    ("            out.build(board, s, &view.state(), me, policy());", "            PONLY_RULES_TO(out);\n            out.build(board, s, &view.state(), me, policy());", 1),
    (V_ENCODE_OLD.format(me="me"), V_ENCODE_NEW.format(me="me"), 1),
    ("        const auto t0=chrono::steady_clock::now();vCalls++;const double v=fSession.evalSimValue(s,turn,g.me);",
     "        if(!vAllowed())return .5;\n        const auto t0=chrono::steady_clock::now();vCalls++;const double v=fSession.evalSimValue(s,turn,g.me);", 1),
    ("    void valueReport(const Game& g)const{", BUDGET_MEMBERS + "    void valueReport(const Game& g)const{", 1),
    ("        if(fSession.model&&fSession.model->value){vDecisions++;",
     "        if(vCut){vFallbacks++;answer=answerH;}  // V was cut in this decision: its choice without V\n"
     "        if(fSession.model&&fSession.model->value){vDecisions++;", 1),
    ("        fSession.update(g);fSession.report(g);valueReport(g);",
     "        vTurnBegin();fSession.update(g);fSession.report(g);valueReport(g);vBudgetReport(g);", 1),
], "v12_ponly.hpp")
write("bots/p_only/bots/v12_ponly_f.hpp", search_experiment.v12(v12f))

c08 = (REPO / "bots/p_only/bots/c08_ponly.hpp").read_text(encoding="utf-8")
c08f = carrier_header("C08 P-only carrier", "c08_ponly.hpp") + apply(c08, [
    ('#include "ponly.hpp"\n', FAMILY_INCLUDES, 1),
    ("#if defined(FUSION_TIER_M)", REGISTRY_FIRST, 1),
    ('#include "models/registry.hpp"\n#endif\n', '#include "models/registry.hpp"\n#endif\n' + FAMILY_TYPES, 1),
    ("        const fusion::PolicyModel* policy() const { return model ? model->policy : nullptr; }",
     "        fusion::Rules rules{};\n        mutable fusion::CombatSummary vcs;  // value v3: one summary per evaluated state, buffers reused\n"
     "        decltype(fusion::models::ModelSet::policy) policy() const { return model ? model->policy : nullptr; }", 1),
    (SESSION_INIT_OLD, "            if (!initialized) { board.init(makeStatic(g)); rules = fusion::rulesOf(makeStatic(g)); "
                       "PONLY_RULES_TO(view); PONLY_RULES_TO(branchView); initialized = true; }", 1),
    ("            out.build(board, s, &view.state(), me, policy(), teams);",
     "            PONLY_RULES_TO(out);\n            out.build(board, s, &view.state(), me, policy(), teams);", 1),
    (V_ENCODE_OLD.format(me="g.me"), V_ENCODE_NEW.format(me="g.me"), 1),
    ("        const auto t0=chrono::steady_clock::now();vCalls[path]++;const double v=fSession.evalGameValue(s);",
     "        if(!vAllowed())return .5;\n        const auto t0=chrono::steady_clock::now();vCalls[path]++;const double v=fSession.evalGameValue(s);", 1),
    ("    void searchReport(const Game& g)const{", BUDGET_MEMBERS + "    void searchReport(const Game& g)const{", 1),
    ("        if(fSession.model&&fSession.model->value){vDecisions[0]++;",
     "        if(vCut){vFallbacks++;answer=answerH;}  // V was cut in this decision: its choice without V\n"
     "        if(fSession.model&&fSession.model->value){vDecisions[0]++;", 1),
    ("                    vDecisions[1]++;if(bestChoice.moveIndex",
     "                    if(vCut){vFallbacks++;bestChoice=choice;}  // V was cut: keep the search's own choice\n"
     "                    vDecisions[1]++;if(bestChoice.moveIndex", 1),
    ("        auto result=planTurn(g,true);fSession.report(g);searchReport(g);",
     "        vTurnBegin();auto result=planTurn(g,true);fSession.report(g);searchReport(g);vBudgetReport(g);", 1),
], "c08_ponly.hpp")
write("bots/p_only/bots/c08_ponly_f.hpp", search_experiment.c08(c08f))
print("wrote ponly_p3.hpp, v12_ponly_f.hpp, c08_ponly_f.hpp" + (f" to {OUT}" if OUT else ""))
