"""Derive the own-action scoring carrier from the family carrier (task T0045, docs/OWN_ACTION_RUNTIME.md).

    python bots/p_only/tools/derive/make_scoring.py        # after make_families.py

Writes bots/p_only/bots/v12_ponly_fs.hpp: v12_ponly_f.hpp with bots/p_only/include/decision_score.hpp in place of
decision_hook.hpp, so that PONLY_DECISION 2 (deployed own-action scoring) exists. Nothing it reads is changed:
v12_ponly_f.hpp, decision_hook.hpp and the log-only carriers stay byte-identical (T0037's frozen identities hash
them). With PONLY_DECISION 0 or 1 the scoring carrier compiles to the family carrier's code. C08 is not derived
yet.

Every replaced text is matched exactly with its expected count, so a changed source is refused, never spliced at
the wrong place. PONLY_DERIVE_DIR redirects the output (tests re-derive and compare).
"""
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
OUT = Path(os.environ["PONLY_DERIVE_DIR"]) if os.environ.get("PONLY_DERIVE_DIR") else None

HEADER = """// Generated by bots/p_only/tools/derive/make_scoring.py from v12_ponly_f.hpp. Do not edit.
// The v12 family carrier with own-action scoring (bots/p_only/include/decision_score.hpp): PONLY_DECISION 2 with an
// exported scorer included first; PONLY_DECISION 0 (default) or 1 is exactly v12_ponly_f.hpp.
"""

MEMBERS = """#if PONLY_DSCORE
#if defined(MOD_FUSION_V) && MOD_FUSION_V
#define PONLY_DSCORE_V 1
#else
#define PONLY_DSCORE_V 0
#endif
    ponly_dscore::Hook dscore;  // own-action scoring of the shortlist (decision_score.hpp)
    static_assert(ponly_dscore::bound(fusion::own_action::exported::kScorer, PONLY_POLICY_FAMILY, PONLY_DSCORE_V),
                  "the own-action scorer was not trained on data of this carrier (PONLY_DSCORE_DATA_CARRIER, opponent-P family, V)");
#endif
"""

EDITS = [
    ('#include "decision_hook.hpp"\n',
     '#include "decision_score.hpp"  // decision_hook.hpp, plus PONLY_DECISION 2 (own-action scoring)\n', 1),
    ("    ponly_decision::Log dlog;  // the shortlist this turn's reply was chosen from (decision_hook.hpp)\n",
     "    ponly_decision::Log dlog;  // the shortlist this turn's reply was chosen from (decision_hook.hpp)\n#endif\n"
     + MEMBERS + "#if PONLY_DECISION\n", 1),
    ("    string decide(Game& g){\n",
     "    string decide(Game& g){\n#if PONLY_DSCORE\n        const auto dscoreStart=chrono::steady_clock::now();\n#endif\n", 1),
    ("        PONLY_DLOG(out+=dlog.comment(out.substr(out.find(' ')+1),ponly_decision::rootDigest(g)));\n",
     "#if PONLY_DSCORE\n        out=dscore.decide(g,fSession,dlog,out,dscoreStart);\n#else\n"
     "        PONLY_DLOG(out+=dlog.comment(out.substr(out.find(' ')+1),ponly_decision::rootDigest(g)));\n#endif\n", 1),
]


def apply(text: str, edits, name: str) -> str:
    for old, new, count in edits:
        n = text.count(old)
        if n != count:
            sys.exit(f"{name}: expected {count} occurrence(s) of {old[:70]!r}, found {n}")
        text = text.replace(old, new)
    return text


def main() -> None:
    src = (REPO / "bots/p_only/bots/v12_ponly_f.hpp").read_text(encoding="utf-8")
    text = HEADER + apply(src, EDITS, "v12_ponly_f.hpp (scoring)")
    path = (OUT or REPO / "bots/p_only/bots") / "v12_ponly_fs.hpp"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote v12_ponly_fs.hpp" + (f" to {OUT}" if OUT else ""))


if __name__ == "__main__":
    main()
