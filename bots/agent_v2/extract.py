"""Generate inference/agent_v2/meowmind_features.hpp: the Meowmind code the frozen meow feature schema needs (T0065).

    python bots/agent_v2/extract.py            # writes the header
    python bots/agent_v2/extract.py --check    # exit 1 if the committed header is not exactly what this generates

The reference is another author's bot (bots/meowmind_p/README.md: "The source carries no license notice"), published
here unmodified at sha256 cc7b730c... (verbatim here except that its CRLF line ends become LF). The agent_v2 carrier is a redesign (docs/AGENT_V2.md): its public state, rules,
predictor, resolver, simulator and search are its own. It keeps only what the frozen actor and value inputs it serves
(feature schemas meow_policy112_v1 and meow_public416_v1, the inputs the existing PPO actors and critics were trained
on) require, copied VERBATIM so they compute exactly what those models saw, inside namespace agent_v2::mm:
  * lines 20-36: the Unit / Flag / Event / Game data structs the feature code reads;
  * lines 173-341: namespace learning: prepared (deterministic respawns) and Geometry (map cache, the 112 actor
    features policy / policyMoves, the 416 value features value).
Nothing else of the reference is used: not its parser, rules simulator, predictor, own policy network, resolver,
hand potential or search.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REFERENCE = REPO / "bots" / "meowmind_p" / "meowmind-ctf-374-20261011.cpp"
REFERENCE_SHA256 = "cc7b730cf77c087c8c7f415b3b7d07101c3f003924d3a845a2ea3b81588794bc"
OUT = REPO / "inference" / "agent_v2" / "meowmind_features.hpp"
RANGES = ((20, 36), (173, 341))


def generate() -> str:
    data = REFERENCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != REFERENCE_SHA256:
        raise SystemExit(f"{REFERENCE} is not the pinned reference (sha256 {REFERENCE_SHA256})")
    # The reference keeps its original CRLF line ends (-text); the repository stores every other file with LF
    # (.gitattributes eol=lf), so the copy is verbatim except for line ends, which are normalized to LF.
    lines = data.decode("utf-8").replace("\r\n", "\n").split("\n")
    parts = []
    for lo, hi in RANGES:
        parts.append(f"// ---- reference lines {lo}-{hi}, verbatim ----")
        parts.extend(lines[lo - 1:hi])
    body = "\n".join(parts)
    return f"""// Generated by bots/agent_v2/extract.py. Do not edit: regenerate (python bots/agent_v2/extract.py).
//
// Verbatim extract of the Meowmind reference bot, bots/meowmind_p/meowmind-ctf-374-20261011.cpp
// (sha256 {REFERENCE_SHA256}), another author's bot published in this
// repository unmodified; the source carries no license notice (bots/meowmind_p/README.md). Lines {RANGES[0][0]}-{RANGES[0][1]} (the data
// structs) and {RANGES[1][0]}-{RANGES[1][1]} (namespace learning: prepared, Geometry with the 112 actor and 416 value features) are
// copied unchanged, inside namespace agent_v2::mm: the frozen feature schemas meow_policy112_v1 / meow_public416_v1
// the existing PPO actors and critics were trained on. Nothing else of the reference is part of the agent_v2 carrier
// (task T0065, docs/AGENT_V2.md). Comments in Chinese are the original author's.
#pragma once
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <string>
#include <utility>
#include <vector>

#ifndef RICH_VALUE
#define RICH_VALUE 1   // the reference's own setting (line 153): value features include the three stay-move policy vectors
#endif

namespace agent_v2::mm {{
using namespace std;

{body}

}}  // namespace agent_v2::mm
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        ok = OUT.is_file() and OUT.read_bytes() == text.encode("utf-8")
        print("meowmind_features.hpp is the verbatim extract" if ok else "meowmind_features.hpp differs: regenerate it")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
