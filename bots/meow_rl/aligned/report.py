"""The predeclared verdicts of the aligned Meowmind RL screens (task T0061, docs/MEOWMIND_RL_ALIGNED.md).

    python bots/meow_rl/aligned/report.py        # reports/host/meow_rl_aligned/VERDICTS.{md,json}

Reads each schedule's committed screen.json (bots/p_only/tools/analyze.py: every comparison's equal-count map-cluster
mean and standard error) and its frozen profile, and judges every comparison under its predeclared family:
  * schedule A: the primary (T0059 large V - aligned warm start) at 95%; the two secondary contrasts (new-pool large V
    - old-pool large V, new-pool large V - new-pool small V) as one Bonferroni family, z = inv_cdf(1 - 0.05 / 4);
  * schedule B: F-D, R-D, H-D, H-R, F-R as one Bonferroni family, z = inv_cdf(1 - 0.05 / 10).
The quantiles are computed, never copied. Differences are utility (pairwise rank utility, 0..1) in percentage points;
an interval containing 0 is "not shown", never "equivalent". A comparison with any scheduled fixture missing for
either arm (or a schedule reported incomplete) gets the verdict "incomplete", never a confirmatory one; its partial
estimate is shown as descriptive only. The A/A re-run rows are reported as they are. Nothing is replayed and no measurement changes; do not edit the output by hand.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SCHEDULES = {"A": REPO / "profiles" / "meow_rl_aligned_screen_a.json", "B": REPO / "profiles" / "meow_rl_aligned_screen_b.json"}
OUT = REPO / "reports" / "host" / "meow_rl_aligned"


def family_z(method: str, alpha: float, k: int) -> float:
    nd = statistics.NormalDist()
    return nd.inv_cdf(1 - alpha / 2) if method == "none" else nd.inv_cdf(1 - alpha / (2 * k))


def verdict(lo: float, hi: float) -> str:
    return "helps" if lo > 0 else "hurts" if hi < 0 else "not shown"


def judge(cfg: dict, screen: dict) -> dict:
    out = {"seed": screen.get("seed"), "schedule": screen.get("schedule"), "fixtures": screen.get("fixtures"),
           "incomplete": screen.get("incomplete"), "families": {}, "rerun_noise": {}}
    for fam, spec in cfg["families"].items():
        comps = [f"{a} - {b}" for a, b in spec["comparisons"]]
        z = family_z(spec["method"], spec["alpha"], len(comps))
        rows = []
        for name in comps:
            c = screen["comparisons"].get(name)
            overall = (c or {}).get("overall")
            if not overall or overall.get("mean") is None or overall.get("se") is None:
                rows.append({"comparison": name, "missing": True, "verdict": "incomplete"})
                continue
            m, se = overall["mean"], overall["se"]
            lo, hi = m - z * se, m + z * se
            complete = not c.get("missing") and not screen.get("incomplete")
            rows.append({"comparison": name, "mean_pp": 100 * m, "se_pp": 100 * se, "lo_pp": 100 * lo, "hi_pp": 100 * hi,
                         "verdict": verdict(lo, hi) if complete else "incomplete", "descriptive_only": not complete,
                         "fixtures": overall.get("fixtures"), "missing_fixtures": c.get("missing")})
        out["families"][fam] = {"method": spec["method"], "alpha": spec["alpha"], "k": len(comps), "z": z, "rows": rows}
    for name, c in screen.get("rerun_noise", {}).items():
        out["rerun_noise"][name] = {"mean_pp": 100 * c["overall"]["mean"], "identical_scores": c.get("identical_scores"),
                                    "fixtures": c.get("fixtures")}
    return out


def main() -> dict:
    result = {"schema": "ctf-meow-rl-aligned-verdicts-1", "generator": "bots/meow_rl/aligned/report.py", "schedules": {}}
    lines = ["# Aligned Meowmind RL screens: predeclared verdicts (T0061)", "",
             "Generated by `bots/meow_rl/aligned/report.py` from each schedule's `screen.json` and frozen profile. Do not edit. "
             "Differences are pairwise rank utility in percentage points (map-cluster standard errors, counts weighted "
             "equally); an interval containing 0 is not shown.", ""]
    for key, path in SCHEDULES.items():
        cfg = json.loads(path.read_text(encoding="utf-8"))
        screen_path = REPO / cfg["report_dir"] / "screen.json"
        if not screen_path.is_file():
            lines += [f"## Schedule {key}", "", f"Not run: `{screen_path.relative_to(REPO)}` does not exist.", ""]
            result["schedules"][key] = None
            continue
        r = judge(cfg, json.loads(screen_path.read_text(encoding="utf-8")))
        result["schedules"][key] = r
        lines += [f"## Schedule {key}", "", f"Seed {r['seed']}, {r['fixtures']} fixtures, incomplete: {r['incomplete'] or 'none'}.", ""]
        for fam, f in r["families"].items():
            rule = "95%" if f["method"] == "none" else f"Bonferroni over {f['k']}, family alpha {f['alpha']}"
            lines += [f"**{fam}** ({rule}, z = {f['z']:.4f})", "", "| Comparison | Mean (pp) | Interval (pp) | Verdict |", "|---|---:|---|---|"]
            for row in f["rows"]:
                if row.get("missing"):
                    lines.append(f"| {row['comparison']} | | | incomplete (no paired estimate) |")
                else:
                    note = f" (descriptive: {row['missing_fixtures']} fixtures missing)" if row["descriptive_only"] else ""
                    lines.append(f"| {row['comparison']} | {row['mean_pp']:+.2f} | [{row['lo_pp']:+.2f}, {row['hi_pp']:+.2f}] | "
                                 f"{row['verdict']}{note} |")
            lines.append("")
        if r["rerun_noise"]:
            lines += ["Re-run (A/A): " + "; ".join(f"`{n}` {v['mean_pp']:+.2f} pp, identical score vectors {v['identical_scores']} of "
                                                  f"{v['fixtures']}" for n, v in r["rerun_noise"].items())
                      + ". Identical replays support repeatability on these fixtures; they do not remove sampling uncertainty.", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "VERDICTS.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8", newline="\n")
    (OUT / "VERDICTS.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return result


if __name__ == "__main__":
    main()
    print(OUT / "VERDICTS.md")
