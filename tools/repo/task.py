from pathlib import Path

FIELDS = ["id", "title", "status", "owner", "needs", "writes", "depends", "land", "branch", "updated"]
LISTS = {"needs", "writes", "depends"}
STATUSES = ("open", "active", "blocked", "review", "done", "dropped")
CAPABILITIES = ("host", "cuda", "ai-test")
SECTIONS = ("Goal", "Done when", "Handoff", "Log")
TASK_FILE = re.compile(r"^(T\d{4})-[a-z0-9-]+\.md$")
AGENT = re.compile(r"^[a-z0-9._-]+@[a-z0-9._-]+$")
DIR = "tasks"
SUMMARY = "SUMMARY.md"
README = "README.md"
ARCHIVE = "archive"
FINISHED = ("done", "dropped")
BOARD_START = "<!-- board:start (generated by tools/repo/task.py with every board change; do not edit) -->"
BOARD_END = "<!-- board:end -->"
DEFAULT_TEST = [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-t", "."]


class BoardError(Exception):
    """A refused board operation: the message says why and what to do."""


# ------------------------------------------------------------------ task files

def parse(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n") or "\n---\n" not in text[3:]:
        raise BoardError("a task file starts with a '---' front matter block")
    end = text.index("\n---\n", 3)
    meta: dict = {}
    for line in text[4:end].split("\n"):
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise BoardError(f"front matter line without 'key: value': {line!r}")
        key, value = key.strip(), value.strip()
        if key in LISTS:
            meta[key] = [v.strip().strip('"') for v in value.strip("[]").split(",") if v.strip()]
        elif value.startswith('"'):
            meta[key] = json.loads(value)
        else:
            meta[key] = "" if value in ("-", "~", "null") else value
    return meta, text[end + len("\n---\n"):]


PLAIN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._@/+-]*$")


def render(meta: dict, body: str) -> str:
    """Front matter that is also valid YAML (GitHub renders it): plain words stay plain, anything else is quoted."""
    lines = ["---"]
    for key in FIELDS:
        value = meta.get(key, [] if key in LISTS else "")
        if key in LISTS:
            text = "[" + ", ".join(v if PLAIN.match(v) else json.dumps(v) for v in value) + "]"
        else:
            text = value if PLAIN.match(value) and key != "title" else json.dumps(value, ensure_ascii=False)
        lines.append(f"{key}: {text}")
    return "\n".join(lines) + "\n---\n" + body


def section_span(body: str, name: str) -> tuple[int, int]:
    m = re.search(rf"^## {re.escape(name)}[ \t]*\n", body, re.M)
    if not m:
        raise BoardError(f"the task has no '## {name}' section")
    nxt = re.search(r"^## ", body[m.end():], re.M)
    return m.end(), (m.end() + nxt.start()) if nxt else len(body)


def set_section(body: str, name: str, text: str) -> str:
    a, b = section_span(body, name)
    return body[:a] + "\n" + text.strip() + "\n\n" + body[b:].lstrip("\n")


def append_log(body: str, line: str) -> str:
    a, b = section_span(body, "Log")
    current, rest = body[a:b].strip(), body[b:].lstrip("\n")
    return body[:a] + "\n" + (current + "\n" if current else "") + line + "\n" + ("\n" + rest if rest else "")


def slugify(title: str, limit: int = 40) -> str:
    words, out = re.findall(r"[a-z0-9]+", title.lower()), ""
    for w in words:
        if out and len(out) + 1 + len(w) > limit:
            break
        out = f"{out}-{w}" if out else w[:limit]
    return out or "task"


def norm(path: str) -> str:
    """Repository-relative form: forward slashes, no leading './' (dot-files such as .github/ keep their dot)."""
    path = path.replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    return path.lstrip("/")


def covers(lane: str, path: str) -> bool:
    lane, path = norm(lane), norm(path)
    return path == lane or path.startswith(lane if lane.endswith("/") else lane + "/")


def overlaps(a: list[str], b: list[str]) -> bool:
    return any(covers(x, y) or covers(y, x) for x in a for y in b)


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%MZ")


def placed(name: str, meta: dict) -> str:
    """Where a task file belongs, relative to tasks/: archive/<file> when finished, else <file>."""
    base = Path(name).name
    return f"{ARCHIVE}/{base}" if meta.get("status") in FINISHED else base


def validate(name: str, meta: dict, body: str, ids: set[str]) -> list[str]:
    """Problems with one task file (empty when valid)."""
    out = []
    m = TASK_FILE.match(name)
    if not m:
        return [f"{name}: file name must be T<4 digits>-<slug>.md"]
    for key in FIELDS:
        if key not in meta:
            out.append(f"{name}: missing field '{key}'")
    if meta.get("id") != m.group(1):
        out.append(f"{name}: id {meta.get('id')!r} does not match the file name")
    if meta.get("status") not in STATUSES:
        out.append(f"{name}: status must be one of {', '.join(STATUSES)}")
    if meta.get("status") == "active" and not AGENT.match(meta.get("owner", "")):
        out.append(f"{name}: an active task needs an owner (tool@machine)")
    if meta.get("status") == "open" and meta.get("owner"):
        out.append(f"{name}: an open task has no owner")
    if meta.get("owner") and not AGENT.match(meta["owner"]):
        out.append(f"{name}: owner must look like tool@machine")
    for cap in meta.get("needs", []):
        if cap not in CAPABILITIES:
            out.append(f"{name}: unknown capability {cap!r} (known: {', '.join(CAPABILITIES)})")
    if not meta.get("writes"):
        out.append(f"{name}: writes must list the paths the task may change")
    for w in meta.get("writes", []):
        if w.startswith("/") or ".." in Path(w).parts:
            out.append(f"{name}: write path {w!r} must be relative to the repository")
    for d in meta.get("depends", []):
        if d not in ids:
            out.append(f"{name}: depends on unknown task {d}")
    if meta.get("land") not in ("direct", "pr"):
        out.append(f"{name}: land must be direct or pr")
    for s in SECTIONS:
        if not re.search(rf"^## {re.escape(s)}[ \t]*$", body, re.M):
            out.append(f"{name}: missing section '## {s}'")
    return out


# ------------------------------------------------------------------ summary

def handoff_line(body: str) -> str:
    """The first sentence-like line of a task's Handoff, without its '*date agent:*' stamp."""
    try:
        a, b = section_span(body, "Handoff")
    except BoardError:
        return ""
    for line in body[a:b].split("\n"):
        line = line.strip()
        if line and not (line.startswith("*") and line.endswith(":*")) and not line.startswith("```"):
            return line if len(line) <= 160 else line[:157].rstrip() + "..."
    return ""


def render_summary(tasks: dict[str, tuple[str, dict, str]]) -> str:
    """tasks/SUMMARY.md: the whole board on one page. Deterministic (no clock), so a stale copy can be detected."""
    rows = sorted(tasks.items())
    done = {t for t, (_, m, _) in rows if m.get("status") == "done"}
    count = lambda s: sum(1 for _, (_, m, _) in rows if m.get("status") == s)           # noqa: E731
    ready = [t for t, (_, m, _) in rows if m.get("status") == "open" and all(d in done for d in m.get("depends", []))]
    merged = [t for t, (_, m, b) in rows if m.get("status") == "dropped" and "Merged into T" in b]
    link = lambda t: f"[{t}]({tasks[t][0]})"                                           # noqa: E731
    cell = lambda s: str(s).replace("|", "\\|")                                       # noqa: E731
    latest = max((m.get("updated", "") for _, (_, m, _) in rows), default="")
    out = ["# Task board summary", "",
           "Generated by `tools/repo/task.py` from `tasks/T*.md` with every board change; do not edit it by hand "
           "(`python tools/repo/task.py summary --write` after a hand edit of a task). How the board works: "
           "[README.md](README.md); the protocol: [AGENTS.md](../AGENTS.md).", "",
           f"**{len(rows)} tasks:** {count('open')} open ({len(ready)} ready to claim), {count('active')} active, "
           f"{count('blocked')} blocked, {count('review')} in review, {count('done')} done, {count('dropped')} dropped "
           f"({len(merged)} of them merged into another task). Latest change: {latest}.", ""]

    def table(title: str, note: str, header: list[str], picked: list[str], cols) -> None:
        out.extend([f"## {title}", ""] + ([note, ""] if note else []))
        if not picked:
            out.extend(["(none)", ""])
            return
        out.append("| " + " | ".join(header) + " |")
        out.append("|" + "---|" * len(header))
        for t in picked:
            name, m, b = tasks[t]
            out.append("| " + " | ".join(cell(c) for c in cols(t, m, b)) + " |")
        out.append("")

    by = lambda *st: [t for t, (_, m, _) in rows if m.get("status") in st]               # noqa: E731
    needs = lambda m: ", ".join(m.get("needs", [])) or "any"                              # noqa: E731
    table("Active, in review, blocked", "Someone holds these; their `writes` are reserved.",
          ["Task", "Status", "Owner", "Title", "Writes"], by("active", "review", "blocked"),
          lambda t, m, b: [link(t), m["status"], m["owner"] or "-", m["title"], ", ".join(m["writes"])])
    table("Ready to claim", "Open, with every dependency done. Claim with `python tools/repo/task.py claim <id>`.",
          ["Task", "Needs", "Title"], ready, lambda t, m, b: [link(t), needs(m), m["title"]])
    waiting = [t for t in by("open") if t not in ready]
    table("Waiting", "Open, but a dependency is not done yet.",
          ["Task", "Needs", "Waits for", "Title"], waiting,
          lambda t, m, b: [link(t), needs(m), ", ".join(d for d in m["depends"] if d not in done), m["title"]])
    table("Done", "The first line of each Handoff: the result, or where it is.",
          ["Task", "Owner", "Title", "Result"], by("done"),
          lambda t, m, b: [link(t), m["owner"] or "-", m["title"], handoff_line(b)])
    table("Dropped and merged", "", ["Task", "Title", "Why"], by("dropped"),
          lambda t, m, b: [link(t), m["title"], handoff_line(b)])
    edges = {t: sorted(o for o, (_, m2, _) in rows if t in m2.get("depends", [])) for t, _ in rows}
    chains = [f"- {link(t)} → " + ", ".join(link(o) for o in after) for t, after in edges.items() if after]
    out.extend(["## What unlocks what", "", "A task on the left must be done before those on the right can start.", ""]
               + (chains or ["(no dependencies)"]) + [""])
    return "\n".join(out)


def render_board(tasks: dict[str, tuple[str, dict, str]], recent: int = 10) -> str:
    """The board section of tasks/README.md: what is going on now. Deterministic, like the summary."""
    rows = sorted(tasks.items())
    done = {t for t, (_, m, _) in rows if m.get("status") == "done"}
    by = lambda *st: [t for t, (_, m, _) in rows if m.get("status") in st]               # noqa: E731
    link = lambda t: f"[{t}]({tasks[t][0]})"                                           # noqa: E731
    cell = lambda s: str(s).replace("|", "\\|")                                       # noqa: E731
    needs = lambda m: ", ".join(m.get("needs", [])) or "any"                              # noqa: E731
    ready = [t for t in by("open") if all(d in done for d in tasks[t][1].get("depends", []))]
    waiting = [t for t in by("open") if t not in ready]
    finished = sorted(by(*FINISHED), key=lambda t: (tasks[t][1].get("updated", ""), t), reverse=True)
    in_archive = any(name.startswith(f"{ARCHIVE}/") for name, _, _ in tasks.values())
    archive = f"[{ARCHIVE}/]({ARCHIVE}/)" if in_archive else f"`{ARCHIVE}/`"       # link the folder once it exists
    out = ["## The board now", "",
           f"**{len(by('active'))} active, {len(by('review'))} in review, {len(by('blocked'))} blocked, "
           f"{len(ready)} ready to claim, {len(waiting)} waiting; {len(by(*FINISHED))} finished** "
           f"(in {archive}). Every board change rewrites this section; the whole board with every "
           f"result is in [SUMMARY.md](SUMMARY.md). Live from any checkout: `python tools/repo/task.py list`.", ""]

    def table(title: str, header: list[str], picked: list[str], cols) -> None:
        out.extend([f"### {title}", ""])
        if not picked:
            out.extend(["(none)", ""])
            return
        out.append("| " + " | ".join(header) + " |")
        out.append("|" + "---|" * len(header))
        for t in picked:
            name, m, b = tasks[t]
            out.append("| " + " | ".join(cell(c) for c in cols(t, m, b)) + " |")
        out.append("")

    table("Being worked on", ["Task", "Status", "Owner", "Title"], by("active", "review", "blocked"),
          lambda t, m, b: [link(t), m["status"], m["owner"] or "-", m["title"]])
    table("Ready to claim", ["Task", "Needs", "Title"], ready, lambda t, m, b: [link(t), needs(m), m["title"]])
    table("Waiting for another task", ["Task", "Needs", "Waits for", "Title"], waiting,
          lambda t, m, b: [link(t), needs(m), ", ".join(d for d in m["depends"] if d not in done), m["title"]])
    table(f"Recently finished (latest {recent})", ["Task", "Status", "Updated", "Title"], finished[:recent],
          lambda t, m, b: [link(t), m["status"], m.get("updated", ""), m["title"]])
    return "\n".join(out)


def with_board(readme: str, tasks: dict[str, tuple[str, dict, str]]) -> str | None:
    """README text with its board section replaced; None when it has no board markers."""
    a, b = readme.find(BOARD_START), readme.find(BOARD_END)
    if a < 0 or b < a:
        return None
    return readme[:a + len(BOARD_START)] + "\n" + render_board(tasks) + "\n" + readme[b:]


# ------------------------------------------------------------------ git

def git(*args: str, cwd: Path, env: dict | None = None, input: bytes | None = None, check: bool = True) -> str:
    r = subprocess.run(["git", *args], cwd=str(cwd), env=env, input=input, capture_output=True)
    if check and r.returncode:
        raise BoardError(f"git {' '.join(args)} failed: {r.stderr.decode(errors='replace').strip()}")
    return r.stdout.decode("utf-8", errors="replace").strip() if r.returncode == 0 else r.stderr.decode(errors="replace")


class Board:
    """The tasks/ folder of <remote>/<branch>, changed only by compare-and-swap pushes."""

    def __init__(self, cwd: Path, remote: str = "origin", branch: str = "main"):
        self.cwd, self.remote, self.branch = Path(cwd), remote, branch
        self.ref = f"refs/remotes/{remote}/{branch}"

    def fetch(self) -> str:
        git("fetch", "-q", self.remote, self.branch, cwd=self.cwd)
        return git("rev-parse", self.ref, cwd=self.cwd)

    def tasks(self, rev: str) -> dict[str, tuple[str, dict, str]]:
        """id -> (file name relative to tasks/, meta, body) at a commit, from tasks/ and tasks/archive/."""
        out = {}
        for sub in ("", f"{ARCHIVE}/"):
            names = git("ls-tree", "--name-only", f"{rev}:{DIR}/{sub}", cwd=self.cwd, check=False)
            for name in names.split("\n") if names and not names.startswith(("fatal", "error")) else []:
                m = TASK_FILE.match(name)
                if m:
                    meta, body = parse(git("show", f"{rev}:{DIR}/{sub}{name}", cwd=self.cwd))
                    out[m.group(1)] = (sub + name, meta, body)
        return out

    def readme(self, rev: str) -> str:
        text = git("show", f"{rev}:{DIR}/{README}", cwd=self.cwd, check=False)
        return "" if text.startswith(("fatal", "error")) else text

    def cas(self, edit, message: str, tries: int = 6) -> tuple[str, object]:
        """edit(tasks) -> ({file name: new text}, result); commit those files on the newest main and push.

        A rejected push means main moved: refetch and recompute (edit raises BoardError if its precondition no
        longer holds). Returns (commit, result)."""
        for attempt in range(tries):
            base = self.fetch()
            before = self.tasks(base)
            changes, result = edit(before)
            if not changes:
                return base, result
            changes = dict(changes)
            for name, text in list(changes.items()):        # a task file goes where its status puts it
                if text is not None and TASK_FILE.match(Path(name).name):
                    want = placed(name, parse(text)[0])
                    if want != name:
                        changes[want], changes[name] = text, None
            after = dict(before)
            for name, text in changes.items():
                m = TASK_FILE.match(Path(name).name)
                if m and text is not None:
                    after[m.group(1)] = (name, *parse(text))
            summary = render_summary(after)
            current = git("show", f"{base}:{DIR}/{SUMMARY}", cwd=self.cwd, check=False)
            if summary.strip() != current.strip():
                changes = {**changes, SUMMARY: summary}
            readme = self.readme(base)
            board = with_board(readme, after)
            if board is not None and board != readme:
                changes = {**changes, README: board}
            with tempfile.TemporaryDirectory() as tmp:
                env = {**os.environ, "GIT_INDEX_FILE": str(Path(tmp) / "index")}
                git("read-tree", base, cwd=self.cwd, env=env)
                for name, text in changes.items():
                    if text is None:
                        git("update-index", "--force-remove", f"{DIR}/{name}", cwd=self.cwd, env=env)
                        continue
                    blob = git("hash-object", "-w", "--stdin", cwd=self.cwd, input=text.encode("utf-8"))
                    git("update-index", "--add", "--cacheinfo", f"100644,{blob},{DIR}/{name}", cwd=self.cwd, env=env)
                tree = git("write-tree", cwd=self.cwd, env=env)
            commit = git("commit-tree", tree, "-p", base, "-m", message, cwd=self.cwd)
            r = subprocess.run(["git", "push", "-q", self.remote, f"{commit}:refs/heads/{self.branch}"], cwd=str(self.cwd),
                               capture_output=True, text=True)
            if r.returncode == 0:
                self.fetch()
                return commit, result
            if not re.search(r"rejected|fetch first|non-fast-forward|stale info|cannot lock ref", r.stderr):
                raise BoardError(f"push to {self.remote}/{self.branch} failed: {r.stderr.strip()}")
            time.sleep(0.5 * (attempt + 1))
        raise BoardError(f"{self.remote}/{self.branch} kept moving; try again")


# ------------------------------------------------------------------ operations (each one compare-and-swap)

def find(tasks: dict, tid: str) -> tuple[str, dict, str]:
    tid = tid.upper()
    if tid not in tasks:
        raise BoardError(f"no task {tid} on the board")
    return tasks[tid]


def op_claim(board: Board, tid: str, agent: str, can: set[str], force: bool = False) -> str:
    def edit(tasks):
        name, meta, body = find(tasks, tid)
        if meta["status"] == "active" and meta["owner"] == agent:
            return {}, meta["branch"]
        if meta["status"] != "open" and not (meta["owner"] == agent or force):
            raise BoardError(f"{tid} is {meta['status']}" + (f", held by {meta['owner']}" if meta["owner"] else "") +
                             "; pick another task or ask the owner to hand it off")
        missing = set(meta["needs"]) - can
        if missing and not force:
            raise BoardError(f"{tid} needs {', '.join(sorted(missing))}, which this machine does not have (CTF_CAN)")
        waiting = [d for d in meta["depends"] if d not in tasks or tasks[d][1]["status"] != "done"]
        if waiting and not force:
            raise BoardError(f"{tid} waits for {', '.join(waiting)}; --force only if the owner of those agrees")
        clash = [f"{o} ({m['owner']})" for o, (_, m, _) in tasks.items()
                 if o != meta["id"] and m["status"] == "active" and overlaps(m["writes"], meta["writes"])]
        if clash and not force:
            raise BoardError(f"{tid} writes where active task {', '.join(clash)} writes; wait, or split the lanes")
        meta = {**meta, "status": "active", "owner": agent, "updated": now()[:10],
                "branch": meta["branch"] or f"{agent.split('@')[0]}/{meta['id'].lower()}-{Path(name).name[6:-3]}"[:80]}
        return {name: render(meta, append_log(body, f"- {now()} {agent}: claimed" + (" (forced)" if force else "")))}, meta["branch"]
    return board.cas(edit, f"tasks: {agent} claims {tid.upper()}\n\nAgent: {agent}")[1]


def op_update(board: Board, tid: str, agent: str, *, status: str | None = None, handoff: str | None = None,
              note: str | None = None, verb: str = "note") -> None:
    def edit(tasks):
        name, meta, body = find(tasks, tid)
        if meta["owner"] and meta["owner"] != agent and status is not None:
            raise BoardError(f"{tid} is held by {meta['owner']}; only the owner changes its status")
        if status:
            meta = {**meta, "status": status, "updated": now()[:10]}
            if status == "open":
                meta["owner"] = ""
            elif status != "dropped" and not meta["owner"]:
                meta["owner"] = agent
        if handoff is not None:
            body = set_section(body, "Handoff", f"*{now()} {agent}:*\n\n{handoff}")
        line = f"- {now()} {agent}: {verb}" + (f" -> {status}" if status and status != verb else "") + (f": {note}" if note else "")
        return {name: render(meta, append_log(body, line))}, None
    board.cas(edit, f"tasks: {agent} {verb} {tid.upper()}" + (f" ({status})" if status and status != verb else "") + f"\n\nAgent: {agent}")


def op_amend(board: Board, tid: str, agent: str, writes: list[str] | None = None, replace: bool = False, *,
             title: str | None = None, depends: list[str] | None = None, needs: list[str] | None = None,
             land: str | None = None, goal: str | None = None, done_when: str | None = None) -> list[str]:
    """Change a task's lanes or its definition: the owner may, and anyone may while it has no owner. Lanes are
    refused where another active task writes. Every change is logged. Returns the task's writes."""
    def edit(tasks):
        name, meta, body = find(tasks, tid)
        if meta["owner"] and meta["owner"] != agent:
            raise BoardError(f"{tid} is held by {meta['owner']}; only the owner changes its lanes or definition")
        new, changed = dict(meta), []
        if writes is not None:
            lanes = [norm(w) for w in writes] if replace else sorted(set(meta["writes"]) | {norm(w) for w in writes})
            if not lanes:
                raise BoardError("a task needs at least one write path")
            clash = [f"{o} ({m['owner']})" for o, (_, m, _) in tasks.items()
                     if o != meta["id"] and m["status"] == "active" and overlaps(m["writes"], lanes)]
            if clash:
                raise BoardError(f"{tid} cannot write there: active task {', '.join(clash)} writes overlapping paths")
            if lanes != meta["writes"]:
                new["writes"] = lanes
                changed.append(f"writes -> {', '.join(lanes)}")
        if depends is not None:
            deps = sorted({d.upper() for d in depends})
            for d in deps:
                find(tasks, d)
            if meta["id"] in deps:
                raise BoardError(f"{tid} cannot depend on itself")
            if deps != meta["depends"]:
                new["depends"] = deps
                changed.append(f"depends -> {', '.join(deps) or 'none'}")
        if needs is not None:
            bad = set(needs) - set(CAPABILITIES)
            if bad:
                raise BoardError(f"unknown capability {', '.join(sorted(bad))} (known: {', '.join(CAPABILITIES)})")
            if sorted(needs) != sorted(meta["needs"]):
                new["needs"] = sorted(needs)
                changed.append(f"needs -> {', '.join(sorted(needs)) or 'any'}")
        if title and title != meta["title"]:
            new["title"] = title
            changed.append(f"title -> {title}")
        if land and land != meta["land"]:
            new["land"] = land
            changed.append(f"land -> {land}")
        for section, text in (("Goal", goal), ("Done when", done_when)):
            if text is not None and text.strip():
                a, b = section_span(body, section)
                if body[a:b].strip() != text.strip():
                    body = set_section(body, section, text)
                    changed.append(section.lower())
        if not changed:
            return {}, meta["writes"]
        new["updated"] = now()[:10]
        return {name: render(new, append_log(body, f"- {now()} {agent}: amended {'; '.join(changed)}"))}, new["writes"]
    return board.cas(edit, f"tasks: {agent} amends {tid.upper()}\n\nAgent: {agent}")[1]


def op_merge(board: Board, keep: str, dups: list[str], agent: str, why: str = "", force: bool = False) -> str:
    """Fold tasks that describe the same work into `keep`, in one commit.

    Each duplicate is closed as dropped, its Handoff pointing to `keep`. `keep`'s Goal gains a 'Merged from'
    paragraph per duplicate with its goal and done-when (only a pointer when the goals match), and its log a line.
    An open `keep` also gains the duplicates' lanes, needs and dependencies; a closed one keeps its record. Tasks
    that depended on a duplicate now depend on `keep`. Refused for a duplicate someone else holds (active, review or
    blocked), and for open work folded into a closed task unless forced."""
    keep = keep.upper()
    dups = [d.upper() for d in dups]
    if not dups or keep in dups or len(set(dups)) != len(dups):
        raise BoardError("merge KEEP DUP [DUP ...]: at least one duplicate, each named once, none equal to KEEP")

    def edit(tasks):
        kname, kmeta, kbody = find(tasks, keep)
        if kmeta["owner"] and kmeta["owner"] != agent and kmeta["status"] in ("active", "review", "blocked"):
            raise BoardError(f"{keep} is held by {kmeta['owner']}; ask them to merge, or merge into another task")
        changes, notes = {}, []
        k_meta = dict(kmeta)
        for d in dups:
            dname, dmeta, dbody = find(tasks, d)
            if dmeta["owner"] and dmeta["owner"] != agent and dmeta["status"] in ("active", "review", "blocked"):
                raise BoardError(f"{d} is {dmeta['status']}, held by {dmeta['owner']}; only they can fold it away")
            open_work = dmeta["status"] not in ("done", "dropped")
            if open_work and kmeta["status"] in ("done", "dropped") and not force:
                raise BoardError(f"{d} is still {dmeta['status']} but {keep} is {kmeta['status']}: its open work would "
                                 "disappear. Merge into an open task, or --force if it really is finished.")
            if kmeta["status"] not in ("done", "dropped"):  # a closed task's record of what it wrote stays as it was
                k_meta["writes"] = sorted(set(k_meta["writes"]) | set(dmeta["writes"]))
                k_meta["needs"] = sorted(set(k_meta["needs"]) | set(dmeta["needs"]))
                k_meta["depends"] = sorted((set(k_meta["depends"]) | set(dmeta["depends"])) - {keep, *dups})
            ka, kb = section_span(kbody, "Goal")
            da, db = section_span(dbody, "Goal")
            wa, wb = section_span(dbody, "Done when")
            same = difflib.SequenceMatcher(None, kbody[ka:kb], dbody[da:db]).ratio() > 0.8
            if same:
                notes.append(f"Merged from {d} ({dmeta['title']}): the same goal, kept here.")
            else:
                notes.append(f"**Merged from {d}: {dmeta['title']}.** {dbody[da:db].strip()}\n\n"
                             f"Done when (from {d}): {dbody[wa:wb].strip()}")
            reason = f"Merged into {keep} ({kmeta['title']}) by {agent}" + (f": {why}" if why else ": the same work.")
            d_meta = {**dmeta, "status": "dropped", "owner": dmeta["owner"] if dmeta["status"] == "done" else "",
                      "updated": now()[:10]}
            dbody = set_section(dbody, "Handoff", f"*{now()} {agent}:*\n\n{reason}")
            changes[dname] = render(d_meta, append_log(dbody, f"- {now()} {agent}: merged into {keep}"))
        if kmeta["status"] == "active":
            clash = [f"{o} ({m['owner']})" for o, (_, m, _) in tasks.items()
                     if o not in (keep, *dups) and m["status"] == "active" and overlaps(m["writes"], k_meta["writes"])]
            if clash:
                raise BoardError(f"{keep} would write where active task {', '.join(clash)} writes; merge later")
        ka, kb = section_span(kbody, "Goal")
        kbody = set_section(kbody, "Goal", kbody[ka:kb].strip() + "\n\n" + "\n\n".join(notes))
        k_meta["updated"] = now()[:10]
        line = f"- {now()} {agent}: merged {', '.join(dups)} into this task" + (f" ({why})" if why else "")
        changes[kname] = render(k_meta, append_log(kbody, line))
        for o, (oname, ometa, obody) in tasks.items():                 # re-point dependencies on the duplicates
            if o in (keep, *dups) or not set(ometa["depends"]) & set(dups):
                continue
            deps = sorted((set(ometa["depends"]) - set(dups)) | {keep})
            changes[oname] = render({**ometa, "depends": deps, "updated": now()[:10]},
                                    append_log(obody, f"- {now()} {agent}: dependency {', '.join(sorted(set(ometa['depends']) & set(dups)))} -> {keep} (merged)"))
        return changes, keep
    return board.cas(edit, f"tasks: {agent} merges {', '.join(dups)} into {keep}\n\nAgent: {agent}")[1]


def op_new(board: Board, agent: str, title: str, needs: list[str], writes: list[str], depends: list[str],
           land: str, goal: str, done_when: str) -> str:
    for cap in needs:
        if cap not in CAPABILITIES:
            raise BoardError(f"unknown capability {cap!r} (known: {', '.join(CAPABILITIES)})")
    if not writes:
        raise BoardError("--writes is required: the paths this task may change")

    def edit(tasks):
        tid = f"T{max([int(t[1:]) for t in tasks] or [0]) + 1:04d}"
        for d in depends:
            find(tasks, d)
        meta = {"id": tid, "title": title, "status": "open", "owner": "", "needs": needs, "writes": [norm(w) for w in writes],
                "depends": [d.upper() for d in depends], "land": land, "branch": "", "updated": now()[:10]}
        body = (f"\n## Goal\n\n{goal or 'TODO: what this task delivers and why.'}\n\n"
                f"## Done when\n\n{done_when or 'TODO: the checks that close it.'}\n\n"
                f"## Handoff\n\nNot started.\n\n## Log\n\n- {now()} {agent}: created\n")
        return {f"{tid}-{slugify(title)}.md": render(meta, body)}, tid
    return board.cas(edit, f"tasks: {agent} creates {title[:50]}\n\nAgent: {agent}")[1]


def op_archive(board: Board, agent: str) -> list[str]:
    """Put every task file where its status belongs (finished ones in tasks/archive/) and refresh the README board."""
    def edit(tasks):
        moved = {name: render(meta, body) for name, meta, body in tasks.values() if placed(name, meta) != name}
        readme = board.readme(board.ref)
        fresh = with_board(readme, tasks)
        if not moved and fresh is not None and fresh != readme:
            return {README: fresh}, []
        return moved, sorted(Path(n).name[:5] for n in moved)
    return board.cas(edit, f"tasks: {agent} archives finished tasks\n\nAgent: {agent}")[1]


