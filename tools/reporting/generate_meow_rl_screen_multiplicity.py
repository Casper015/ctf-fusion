"""Generate reports/host/meow_rl_screen/secondary/MULTIPLICITY.md: the secondary screen under its predeclared rule.

    python tools/reporting/generate_meow_rl_screen_multiplicity.py

T0057's secondary screen (profiles/meow_rl_screen_secondary.json) predeclared one family of comparisons judged with
Bonferroni intervals, but its analysis (bots/p_only/tools/analyze.py before T0060) applied 95% intervals. This script
reads only the committed screen.json (each comparison's equal-count mean and standard error) and the frozen config,
and states every comparison under both: no game is replayed and no measurement changes. Bands and per-count rows stay
descriptive (they were never part of the family). Do not edit the output by hand.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCREEN = REPO / "reports" / "host" / "meow_rl_screen" / "secondary"
CONFIG = REPO / "profiles" / "meow_rl_screen_secondary.json"


def verdict(mean: float, half: float) -> str:
    lo, hi = mean - half, mean + half
    return "helps" if lo > 0 else "hurts" if hi < 0 else "not shown"


def main() -> Path:
    screen = json.loads((SCREEN / "screen.json").read_text(encoding="utf-8"))
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    rule = cfg["multiplicity"]
    comps = screen["comparisons"]
    k = len(comps)
    if rule["method"] != "bonferroni" or k != rule["family"]:
        raise SystemExit(f"config rule {rule} does not describe the {k} comparisons in screen.json")
    z95 = statistics.NormalDist().inv_cdf(0.975)
    z = statistics.NormalDist().inv_cdf(1 - rule["alpha"] / (2 * k))
    if abs(z - rule["z"]) > 5e-4:
        raise SystemExit(f"config z {rule['z']} differs from Bonferroni z {z:.4f}")
    out = ["# Secondary screen under its predeclared multiplicity rule", "",
           "Generated by `tools/reporting/generate_meow_rl_screen_multiplicity.py` from `screen.json` and "
           "`profiles/meow_rl_screen_secondary.json`. Do not edit.", "",
           f"The secondary schedule predeclared **{k} comparisons as one family, Bonferroni, family alpha {rule['alpha']}**: "
           f"each comparison is judged on its two-sided interval with z = {z:.4f} (mean ± z × se, the equal-count map "
           "standard error of bots/p_only/tools/analyze.py). `SCREEN.md` (T0057) shows 95% intervals (z = 1.96); this table "
           "is the predeclared verdict. Same games, same estimates: only the interval width changes.", "",
           f"Schedule `{screen['schedule'][:16]}…`, seed {screen['seed']}, {screen['fixtures']} fixtures, "
           f"incomplete: {screen['incomplete'] or 'none'}.", "",
           "| Comparison | Mean | se | 95% interval | 95% verdict | Bonferroni interval | **Predeclared verdict** |",
           "|---|---:|---:|---|---|---|---|"]
    changed = []
    for name, c in comps.items():
        o = c["overall"]
        m, se = o["mean"], o["se"]
        v95, vb = verdict(m, z95 * se), verdict(m, z * se)
        if v95 != vb:
            changed.append(name)
        out.append(f"| {name} | {m:+.5f} | {se:.5f} | [{m - z95 * se:+.4f}, {m + z95 * se:+.4f}] | {v95} | "
                   f"[{m - z * se:+.4f}, {m + z * se:+.4f}] | **{vb}** |")
    out += ["", "Changed by the predeclared rule: " + (", ".join(f"`{n}`" for n in changed) if changed else "none") + ".", "",
            "Re-run noise (A/A) is a diagnostic, not part of the family: "
            + "; ".join(f"`{n}` mean {c['overall']['mean']:+.5f}, identical score vectors {c['identical_scores']} of {c['fixtures']}"
                        for n, c in screen["rerun_noise"].items()) + ".", ""]
    path = SCREEN / "MULTIPLICITY.md"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    return path


if __name__ == "__main__":
    print(main())
