"""Generate reports/host/meow_rl_pool2/REPORT.md from the T0059 receipts (never edit the report by hand).

    python tools/reporting/generate_meow_rl_pool2_report.py

Inputs (all committed): reports/host/meow_rl_pool2/RECEIPTS.json, {large_v,small_v}_smoke_report.json,
reports/models/meow_rl_pool2/MANIFEST.json and the training pool the receipts name. Every number and hash in the report
is read from them; the script refuses inputs that disagree (checkpoint hashes in receipts vs manifest, the pool file's
sha256 vs the receipts). Training diagnostics are descriptive: they are not admission or strength evidence.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HOST = REPO / "reports" / "host" / "meow_rl_pool2"
MODELS = REPO / "reports" / "models" / "meow_rl_pool2"
ARMS = ("large_v", "small_v")


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def posix(p: str) -> str:
    return p.replace("\\", "/")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> Path:
    rc, mf = load(HOST / "RECEIPTS.json"), load(MODELS / "MANIFEST.json")
    smoke = {arm: load(HOST / f"{arm}_smoke_report.json") for arm in ARMS}
    pool_path = REPO / posix(rc["artifacts"]["pool"]["path"])
    if sha256(pool_path) != rc["artifacts"]["pool"]["sha256"]:
        raise SystemExit(f"{pool_path} differs from the receipts' pool sha256")
    pool = load(pool_path)
    for arm in ARMS:
        r, m = rc["arms"][arm]["checkpoints"], mf["checkpoints"][arm]
        for name in sorted(set(r) | set(m)):
            rh = r.get(name, {}).get("sha256") if isinstance(r.get(name), dict) else r.get(name)
            if rh != m.get(name, {}).get("sha256"):
                raise SystemExit(f"{arm}/{name}: receipts and manifest disagree")
    cfg = {arm: rc["arms"][arm]["config"] for arm in ARMS}
    cnt = {arm: rc["arms"][arm]["counters"] for arm in ARMS}
    met = {arm: rc["arms"][arm]["metrics"] for arm in ARMS}
    mach = rc["machine"]
    out = ["# Meowmind PPO training pool v2 (AI_Test lineages) host run (T0059)", "",
           "Generated by `tools/reporting/generate_meow_rl_pool2_report.py` from `RECEIPTS.json`, the smoke reports, "
           "`reports/models/meow_rl_pool2/MANIFEST.json` and the training pool. Do not edit.", "",
           "**Status.** Two training runs of the Meowmind RL pipeline on training pool v2 (AI_Test lineages): the "
           "large-V primary and the small-V ablation, 1,000,000 learner decisions each with `--keep-features`, smoke included. Training "
           "losses and utilities against the training pool are diagnostics only: they are not admission evidence and do "
           "not compare the arms (different seed bases, single-update means). The deployment comparison is T0057's "
           "screen (docs/MEOWMIND_RL_DEPLOYMENT.md, T0056).", "",
           "## Run", "",
           "| | large_v | small_v |", "|---|---|---|"]
    rows = [("Critic", lambda a: f"`{cfg[a]['identity']['critic']}`"),
            ("Seed base (ledgered)", lambda a: str(cfg[a]["seed_base"])),
            ("Optimizer seed", lambda a: str(cfg[a]["optimizer_seed"])),
            ("Decisions / updates / episodes", lambda a: f"{cnt[a]['decisions']:,} / {cnt[a]['updates']} / {cnt[a]['episodes']:,}"),
            ("Rollout target per update", lambda a: f"{cfg[a]['rollout_decisions']:,}"),
            ("Workers / opponent limits", lambda a: f"{cfg[a]['workers']} / {cfg[a]['limits'][0] * 1000:g} ms, {cfg[a]['limits'][1] * 1000:g} ms"),
            ("Device", lambda a: f"{cfg[a]['device'].get('gpu')}, torch {cfg[a]['device'].get('torch')}, TF32 {cfg[a]['device'].get('tf32')}"),
            ("Code digest (training/meow_rl, tools/cpp/meow_rl)", lambda a: f"`{cfg[a]['sources']['code_digest'][:16]}`"),
            ("Engine sha256 / arena commit", lambda a: f"`{cfg[a]['engine']['sha256'][:12]}` / `{cfg[a]['engine']['commit'][:12]}`"),
            ("Development run", lambda a: str(cfg[a]["dev"]))]
    out += [f"| {k} | {f('large_v')} | {f('small_v')} |" for k, f in rows]
    out += ["", f"Host `{mach['hostname']}`, {mach['gpu']} ({mach['vram_mb']} MB), {mach['cpu_threads']} CPU threads, "
                f"{mach['os']}; repository commit `{rc['git']['repo_commit'][:12]}`.", "",
            "## Integrity", "",
            "| | large_v | small_v |", "|---|---|---|",
            f"| Faults (all seats) | {cnt['large_v']['faults']} | {cnt['small_v']['faults']} |",
            f"| Discarded episodes / decisions | {cnt['large_v']['discarded_episodes']} / {cnt['large_v']['discarded_decisions']} | "
            f"{cnt['small_v']['discarded_episodes']} / {cnt['small_v']['discarded_decisions']} |"]
    for key, label in (("max_logp_recompute_gap", "Smoke: largest log-probability recompute gap"),
                       ("nonzero_actor_grad", "Smoke: non-zero actor gradient"), ("nonzero_critic_grad", "Smoke: non-zero critic gradient"),
                       ("state_round_trip", "Smoke: exact state round trip"), ("all_finite", "Smoke: finite losses")):
        out.append(f"| {label} | {smoke['large_v']['checks'][key]} | {smoke['small_v']['checks'][key]} |")
    fams = sorted({b["family"] for b in pool["bots"]})
    out += ["", "## Opponent pool and realized coverage", "",
            f"Pool `{posix(rc['artifacts']['pool']['path'])}` (sha256 `{rc['artifacts']['pool']['sha256'][:16]}`, cap "
            f"{pool['family_cap']}).", "", "| Family | Bots | large_v seats | share | small_v seats | share |",
            "|---|---|---:|---:|---:|---:|"]
    tot = {a: sum(cnt[a]["families"].values()) for a in ARMS}
    for f in fams:
        bots = ", ".join(b["name"] for b in pool["bots"] if b["family"] == f)
        cells = [f"{cnt[a]['families'].get(f, 0):,} | {cnt[a]['families'].get(f, 0) / tot[a]:.2%}" for a in ARMS]
        out.append(f"| {f} | {bots} | {cells[0]} | {cells[1]} |")
    out += [f"| total | | {tot['large_v']:,} | | {tot['small_v']:,} | |", "", "Games per team count:", "",
            "| Arm | " + " | ".join(str(c) for c in range(2, 16)) + " |", "|---|" + "---:|" * 14]
    for a in ARMS:
        out.append(f"| {a} | " + " | ".join(str(cnt[a]["counts"].get(str(c), 0)) for c in range(2, 16)) + " |")
    out += ["", "## Training diagnostics (descriptive)", "",
            "Per-update means against the training pool; the first and last are single updates (about 21 episodes each).", "",
            "| | large_v | small_v |", "|---|---:|---:|"]
    for key in ("utility_initial", "utility_final", "utility_mean", "utility_max", "v_loss_initial", "v_loss_final",
                "v_loss_mean", "approx_kl_mean", "approx_kl_max", "total_collect_s", "total_learn_s"):
        out.append(f"| {key} | {met['large_v'][key]:.4g} | {met['small_v'][key]:.4g} |")
    out += ["", "Value losses belong to different critics on different data and are not comparable as residual variance.", "",
            "## Checkpoints (MANIFEST.json)", "", "| Arm | File | Bytes | sha256 |", "|---|---|---:|---|"]
    for a in ARMS:
        for name, c in sorted(mf["checkpoints"][a].items()):
            out.append(f"| {a} | `{name}` | {c['bytes']:,} | `{c['sha256']}` |")
    out += ["", f"Predeclared candidates: large_v `{mf['primary_candidate']['path']}`, small_v `{mf['control_candidate']['path']}`.", "",
            "## Backup and lineage", "",
            f"- Primary durable backup `{posix(rc['artifacts']['durable_backup']['path'])}` ({rc['artifacts']['durable_backup']['bytes']:,} bytes, "
            f"sha256 `{rc['artifacts']['durable_backup']['sha256'][:16]}`) is archived.",
            f"- Off-machine copy preserved at `{rc['artifacts']['durable_backup']['off_machine_copy']}`.",
            "- Both runs used `--keep-features`: all 120 update batches retain full actor and value feature snapshots.",
            "-opponents drawn from pool v2 (50 bots across 9 lineages, including AI_Test Astra, Player5, Player1, Player3 families).",
            "- Receipt paths use POSIX/Windows normalization."]
    path = HOST / "REPORT.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    return path


if __name__ == "__main__":
    print(main())
