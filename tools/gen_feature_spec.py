TITLE = {"global": "Global (per team)", "unit": "Policy: unit (per own unit, 3 rows by id)",
         "move": "Policy: move (per own unit and move S U D L R)",
         "cand_f": "Policy: attack candidate (per own unit, up to 8 hittable enemies within 4, nearest first)",
         "value_unit": "Value: own unit (same meaning as the policy unit features)", "value_agg": "Value: aggregates"}


def render() -> str:
    s = schema()
    out = ["# Feature spec v%d" % s["spec_version"], "",
           "Generated by `tools/gen_feature_spec.py` from `extract_features --schema`; do not edit by hand.", "",
           "`inference/features.hpp` is the only implementation. The training extractor (`tools/extract_features.cpp`)",
           "and the bot call the same functions. Every feature is a clipped integer in [lo, hi]. Training divides by",
           "`scale`; the exporter folds that division into the first layer, so inference is integer and exact.", "",
           "Facts shared by all features of a turn (`makeView` in `inference/state.hpp`):", "",
           "- **origin**: the cell a unit moves from this turn. A dead unit whose respawn time has come takes the first free",
           "  cell of its team's spawn order (engine phase 1, ascending unit id) and is `immune` this turn. Tests check every",
           "  prediction against the engine's respawn events.",
           "- **available flag**: home, or dropped with `turn < return_at` (a dropped flag at its return time moves to a",
           "  random spot in phase 1, so it cannot be picked up where it lies).",
           "- **shooter**: on the board, not respawning, not carrying. **hittable**: on the board, not respawning.",
           "- Distances: BFS over open cells for base and flag distances, Manhattan for ranges; `canAttack` is engine",
           "  `Game.can_attack`.", "",
           "## Model inputs", "",
           "| Net | Input | Width |", "|---|---|---:|"]
    G, U, M = len(s["global"]), len(s["unit"]), len(s["move"])
    V = G + 3 * len(s["value_unit"]) + len(s["value_agg"])
    out += [f"| P mover (per unit, per legal move) | global + unit k + move (k, m) | {G + U + M} |",
            f"| P squad (per team) | global + 3 units + 15 moves | {G + 3 * U + 15 * M} |",
            f"| P act (per unit, per move) | same as mover; output wait/pickup/drop/attack masked by `act_legal` | {G + U + M} |",
            "| P target (per unit, candidate, move) | dist, hp, carrying, support, hit bit of the move, attacked_by_team, target_home | 7 |",
            f"| V (per team) | global + 3 value units + value aggregates | {V} |", "",
            "V's first layer (128 wide) is the accumulator: `inference/value.hpp` keeps its int32 pre-activations and",
            "updates them per changed feature (`ValueAccumulator`), bit-identical to the full pass.", ""]
    for g in ("global", "unit", "move", "cand_f", "value_unit", "value_agg"):
        out += [f"## {TITLE[g]}", "", "| # | name | lo | hi | scale | meaning |", "|---:|---|---:|---:|---:|---|"]
        for i, (n, lo, hi, sc) in enumerate(s[g]):
            out.append(f"| {i} | `{n}` | {lo} | {hi} | {sc} | {DESC[g].get(n, '')} |")
        out.append("")
    out += ["## Extractor record (int16, one per turn and team)", "", "| block | offset | shape |", "|---|---:|---|"]
    for name, off, shape in s["layout"]:
        out.append(f"| `{name}` | {off} | {' x '.join(map(str, shape))} |")
    out += ["", f"Record width {s['record_width']}. `legal`, `act_legal` are 0/1 masks; `origin` is a cell index",
            "(y*size+x, -1 off the board); `cand` holds enemy unit ids (-1 = empty slot).", "",
            "Changing any feature, range or order is a new spec version: bump `kSpecVersion`, retrain, re-export, and",
            "regenerate this file. Exported headers `static_assert` the version they were trained on; datasets, warm",
            "starts, evaluation and export refuse runs or shards built with another version.", "",
            "**v2** (from v1) adds the score-distribution value aggregates `rivals_tied`, `rivals_1_2_ahead`,",
            "`rivals_1_2_behind` and `pairwise_now`. Under v1, team 0 with scores [5,6,4] and [5,6,5] had identical",
            "value inputs although the outcome target differs (0.5 and 0.25 if nobody scores again).", ""]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is stale: run python tools/gen_feature_spec.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
