"""Build the native diagnostic tool and continuation bot of one agent_v2 package (task T0085).

    python -m tools.search_diagnostics.build p2general --out build/search_diagnostics

Each package in packages.json names the defines and headers of a committed variant. A generated wrapper defines them,
includes the actor (and, for the root tool, the critic) header, then the native source; bots/p_only/tools/bundle.py
inlines every local include into one .cpp, whose SHA-256 is the program's identity, and the binary is compiled with
the repository's flags (fusion/runner.py). The returned identity records the package, the bundle and binary hashes,
every inlined file with its hash, and the compiler; a collection pins it in its manifest.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

from fusion import runner
from fusion.paths import REPO
from tools.search_diagnostics.schemas import ValidationError, sha256_file, sha256_text

HERE = Path(__file__).resolve().parent
PACKAGES = HERE / "packages.json"
NATIVE = {"root_tool": HERE / "native" / "diag_tool.cpp", "continuation_bot": HERE / "native" / "continuation_bot.cpp"}


def load_packages(path: Path = PACKAGES) -> dict:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    for name, p in data["packages"].items():
        for key in ("defines", "actor", "critic", "production_variant"):
            if key not in p:
                raise ValidationError(f"package {name} has no {key}")
        for key in ("actor", "critic", "production_variant"):
            if not (REPO / p[key]).is_file():
                raise ValidationError(f"package {name}: {p[key]} does not exist")
    return data


def wrapper(package: dict, program: str, tree: tuple[int, int]) -> str:
    lines = [f"// Generated by tools/search_diagnostics/build.py: {program}. Do not edit."]
    lines += [f"#define {k} {v}" for k, v in package["defines"].items()]
    if program == "root_tool":
        lines += [f"#define AGENT_V2_SEARCH_CANDIDATES {tree[0]}", f"#define AGENT_V2_SEARCH_SAMPLES {tree[1]}"]
    lines.append(f'#include "{(REPO / package["actor"]).as_posix()}"')
    if program == "root_tool":
        lines.append(f'#include "{(REPO / package["critic"]).as_posix()}"')
    lines.append(f'#include "{NATIVE[program].as_posix()}"')
    return "\n".join(lines) + "\n"


def rel(p: Path) -> str:
    p = Path(p).resolve()
    return p.relative_to(REPO).as_posix() if p.is_relative_to(REPO) else p.as_posix()


def build_program(name: str, program: str, out: Path, packages: dict | None = None) -> dict:
    """Bundle and compile one program of package `name`; the identity record of the binary."""
    sys.path.insert(0, str(REPO / "bots" / "p_only" / "tools"))
    from bundle import bundle  # noqa: PLC0415

    packages = packages or load_packages()
    if name not in packages["packages"]:
        raise ValidationError(f"unknown package {name}; known: {sorted(packages['packages'])}")
    package = packages["packages"][name]
    tree = (int(packages["tree_candidates"]), int(packages["tree_samples"]))
    out = Path(out)
    gen = out / "src" / f"{name}_{program}_wrapper.cpp"
    gen.parent.mkdir(parents=True, exist_ok=True)
    gen.write_text(wrapper(package, program, tree), encoding="utf-8", newline="\n")
    text, files = bundle(gen)
    digest = sha256_text(text)
    src = out / "src" / f"{name}_{program}.cpp"
    src.write_text(text, encoding="utf-8", newline="\n")
    exe = out / "bin" / f"{name}_{program}-{digest[:12]}{runner.EXE}"
    exe.parent.mkdir(parents=True, exist_ok=True)
    cxx = runner.find_compiler()
    if not cxx:
        raise ValidationError("no C++ compiler found (install g++/clang++ or w64devkit, or set CXX)")
    if not exe.is_file():
        tmp = exe.with_name(exe.stem + f".tmp{os.getpid()}{runner.EXE}")
        r = subprocess.run([cxx, *runner.CXX_FLAGS, str(src), "-o", str(tmp)], capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=900)
        if r.returncode != 0:
            raise ValidationError(f"compile failed for {name} {program}:\n{(r.stderr or r.stdout)[-3000:]}")
        os.replace(tmp, exe)
    version = subprocess.run([cxx, "--version"], capture_output=True, text=True)
    return {
        "package": name, "program": program, "role": package["role"], "defines": package["defines"],
        "tree": list(tree) if program == "root_tool" else None,
        "bundle": rel(src), "bundle_sha256": digest, "binary": rel(exe), "binary_sha256": sha256_file(exe),
        "compiler": (version.stdout or version.stderr).splitlines()[0] if (version.stdout or version.stderr) else cxx,
        "flags": list(runner.CXX_FLAGS),
        "inputs": sorted(({"path": rel(f), "sha256": sha256_file(f)} for f in files if Path(f) != gen),
                         key=lambda x: x["path"]),
    }


def build_package(name: str, out: Path) -> dict:
    packages = load_packages()
    return {program: build_program(name, program, out, packages) for program in NATIVE}


def binary_path(identity: dict) -> Path:
    """The binary of an identity record, refused when it no longer has the recorded hash."""
    p = Path(identity["binary"])
    p = p if p.is_absolute() else REPO / p
    if not p.is_file():
        raise ValidationError(f"{identity['binary']} is missing")
    if sha256_file(p) != identity["binary_sha256"]:
        raise ValidationError(f"{identity['binary']} changed since it was recorded")
    return p


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("package")
    ap.add_argument("--out", default=str(REPO / "build" / "search_diagnostics"))
    a = ap.parse_args(argv)
    ids = build_package(a.package, Path(a.out))
    print(json.dumps({k: {f: v[f] for f in ("binary", "binary_sha256", "bundle_sha256")} for k, v in ids.items()}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
