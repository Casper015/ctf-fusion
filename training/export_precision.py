"""Export an opponent policy in an experimental precision profile (task T0030, docs/P_MIXED_PRECISION.md).

    python -m training.export_precision export --policy runs/pf_p2_xxl_s1 --profile uniform8 --name pxxl
    python -m training.export_precision export --policy RUN --profile mixed4_8 --importance build/p_precision/imp.npz
    python -m training.export_precision bench-plan --header build/p_precision/pxxl/mixed4_8/policy_lp.hpp

Writes, under build/p_precision/<name>/<profile>/ (ignored by git; a later model task decides what to commit):
  policy_lp.hpp   constexpr low-bit arrays and one fusion::PolicyModelLP (`fusion::lpmodels::<ns>::model`)
  arrays.npz      the same arrays (fusion/precision.py flatten), for the emulation and parity tests
  MANIFEST.json   format, profile and profile identity, feature family, weights digest, header SHA-256, numeric
                  metadata per layer (bits, bounds, shifts), storage measured from the arrays, policy source

reference16 is the existing INT16 export (training/export_weights.py): this command refuses it rather than write
a second copy of it. The digest of every array and the header hash form one identity, which the header carries
(kManifestIdentity) and the native build cache keys on (fusion/native.py hashes every dependency).

`bench-plan` prints the reproducible benchmark command and its identities (CPU, compiler, flags, concurrency,
header, profile) for a later host task; it does not time anything.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
from pathlib import Path

import numpy as np

from fusion import families, precision
from fusion.paths import BUILD
from fusion.schema import layout as feature_layout

OUT = BUILD / "p_precision"
CTYPES = {np.dtype(np.int8): "int8_t", np.dtype(np.uint8): "uint8_t", np.dtype(np.int16): "int16_t",
          np.dtype(np.int32): "int32_t", np.dtype(np.float64): "double"}


def _values(a: np.ndarray) -> str:
    flat = np.ascontiguousarray(a).reshape(-1)
    if flat.dtype == np.float64:
        return ", ".join(float(v).hex() for v in flat)
    return ", ".join(str(int(v)) for v in flat)


def _array(name: str, a: np.ndarray) -> str:
    return f"inline constexpr {CTYPES[a.dtype]} {name}[{max(a.size, 1)}] = {{{_values(a) if a.size else '0'}}};"


def emit_nets(nets: dict[str, dict]) -> list[str]:
    """C++ arrays, layer tables and lowbit::Net values for the given nets (inside the caller's namespace)."""
    out = []
    for name, net in nets.items():
        rows = []
        for i, L in enumerate(net["layers"]):
            arr = precision.layer_arrays(L)
            p = f"{name}_{i}"
            for k in ("w", "d", "b", "mult", "out_scale"):
                if k in arr:
                    out.append(_array(f"{p}_{k}", arr[k]))
            rows.append("    {" + ", ".join([
                str(L["bits"]), str(L["in"]), str(L["out"]), str(L["in_pad"]), f"{p}_w",
                f"{p}_d" if L["bits"] == 4 else "nullptr", f"{p}_b", "true" if L["hidden"] else "false",
                f"{p}_mult" if L["hidden"] else "nullptr", str(L.get("rshift", 0)),
                "nullptr" if L["hidden"] else f"{p}_out_scale"]) + "},")
            out.append(f"static_assert({L['in_pad']} <= fusion::kMaxWidth && {L['out']} <= fusion::kMaxWidth, "
                       f"\"{name} layer {i} is wider than FUSION_MAX_WIDTH\");")
        out.append(f"inline const fusion::lowbit::Layer {name}_layers[] = {{\n" + "\n".join(rows) + "\n};")
        out.append(f"inline const fusion::lowbit::Net {name}{{{name}_layers, {len(net['layers'])}}};")
    return out


def header(qp: dict, ns: str, identity: dict) -> str:
    fam = 3 if qp["family"] == "p3" else 2
    widths = ("fusion::kMoverInP3", "fusion::kSquadInP3") if fam == 3 else ("fusion::kMoverIn", "fusion::kSquadIn")
    digest = identity["weights_digest"]
    lines = [
        "// Generated by training/export_precision.py; do not edit. Experimental (task T0030): build/ only.",
        f"// profile {qp['profile']} ({qp['identity']}), family {qp['family']}, format {precision.FORMAT_VERSION}",
        "#pragma once",
        '#include "policy_precision/policy_lp.hpp"',
        '#include "policy_p3.hpp"' if fam == 3 else '#include "policy.hpp"',
        f"namespace fusion::lpmodels::{ns} {{",
        f'inline constexpr char kManifestIdentity[] = "{digest}";',
        f'inline constexpr char kProfile[] = "{qp["profile"]}";',
        *emit_nets(qp["nets"]),
        # The family's input widths, checked against the encoders at compile time (p2 and p3 never meet).
        f'static_assert({qp["nets"]["mover"]["in"]} == {widths[0]}, "mover input is not family {qp["family"]}");',
        f'static_assert({qp["nets"]["squad"]["in"]} == {widths[1]}, "squad input is not family {qp["family"]}");',
        f"inline const fusion::PolicyModelLP model{{mover, squad, act, target, {fam}, "
        f"0x{digest[:16]}ull, 0x{qp['identity']}ull}};",
        "}  // namespace",
        "",
    ]
    return "\n".join(lines)


def check_family(qp: dict, layout) -> None:
    """Refuse nets whose input widths are not the declared feature family's (p2 weights never meet p3 features)."""
    from fusion.models import policy_widths  # noqa: PLC0415

    want = policy_widths(layout, qp["family"])
    for h in precision.HEADS:
        got = qp["nets"][h]["in"]
        if got != want[h]:
            raise ValueError(f"{h} input width {got} is not family {qp['family']}'s {want[h]}")


def export(policy, layout, profile: str, out_dir: Path, ns: str, importance: dict | None = None,
           sources: dict | None = None) -> dict:
    if precision.PROFILES[profile].get("legacy"):
        raise SystemExit("reference16 is the existing INT16 export (training/export_weights.py); not duplicated here")
    qp = precision.quantize_policy(policy, layout, profile, importance=importance)
    check_family(qp, layout)
    ident = precision.manifest_identity(qp, sources)
    out_dir.mkdir(parents=True, exist_ok=True)
    text = header(qp, ns, ident)
    (out_dir / "policy_lp.hpp").write_text(text, encoding="utf-8", newline="\n")
    flat = precision.policy_flat(qp)
    np.savez(out_dir / "arrays.npz", **flat)
    manifest = {
        **ident,
        "header_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "namespace": f"fusion::lpmodels::{ns}",
        "layers": {h: [{k: L[k] for k in ("bits", "in", "out", "in_pad", "bound")} | {"rshift": L.get("rshift")}
                       for L in net["layers"]] for h, net in qp["nets"].items()},
        "storage": precision.policy_storage(qp),
        "importance": "activation second moments (fusion/precision_calib.py)" if importance else "max-abs",
    }
    (out_dir / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, sort_keys=True), encoding="utf-8")
    return manifest


def bench_plan(header_path: Path, workers: int, profile: str) -> dict:
    """The reproducible benchmark command for a later host task, with every identity it depends on."""
    from fusion.native import FLAGS, compiler  # noqa: PLC0415

    text = Path(header_path).read_bytes()
    return {"command": ["python", "-m", "training.export_precision", "bench", "--header", str(header_path),
                        "--namespace", "<namespace in the header>", "--iterations", "10000", "--workers", str(workers)],
            "tool": "tools/cpp/precision_bench.cpp", "header_sha256": hashlib.sha256(text).hexdigest(),
            "profile": profile, "cpu": platform.processor() or platform.machine(), "system": platform.platform(),
            "compiler": compiler(), "flags": list(FLAGS), "concurrency": workers,
            "measures": ["startup (first call, cold)", "warm full-reply forward per head", "weight bytes per call",
                         "activation bytes per call"],
            "status": "planned, not run (task T0030 runs no timing)"}


def bench_binary(header_path: Path, namespace: str) -> Path:
    """tools/cpp/precision_bench.cpp compiled against one exported header, cached under build/ by the hash of every
    source it includes. The host runs it (a later task); T0030 only builds it."""
    import subprocess  # noqa: PLC0415

    from fusion.native import FLAGS, compiler  # noqa: PLC0415
    from fusion.paths import REPO  # noqa: PLC0415

    header_path = Path(header_path).resolve()
    tool = REPO / "tools" / "cpp" / "precision_bench.cpp"
    h = hashlib.sha256(header_path.read_bytes() + tool.read_bytes() + " ".join(FLAGS).encode())
    for dep in sorted((REPO / "inference" / "policy_precision").glob("*.hpp")) + sorted((REPO / "inference").glob("*.hpp")):
        h.update(dep.read_bytes())
    out = BUILD / f"precision_bench_{namespace}_{h.hexdigest()[:12]}"
    if not out.is_file():
        cmd = [compiler(), *FLAGS, f"-DPBENCH_NS={namespace}", f"-I{REPO / 'inference'}", "-include", str(header_path),
               str(tool), "-o", str(out)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError(f"compile failed: {' '.join(cmd)}\n{r.stderr[-3000:]}")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("--policy", type=Path, required=True)
    e.add_argument("--profile", choices=[p for p, v in precision.PROFILES.items() if not v.get("legacy")], required=True)
    e.add_argument("--name", required=True)
    e.add_argument("--importance", type=Path, help="npz from fusion/precision_calib.py (head.layer -> importance)")
    r = sub.add_parser("bench", help="build the benchmark binary; --run executes it (a host task, not T0030)")
    r.add_argument("--header", type=Path, required=True)
    r.add_argument("--namespace", required=True)
    r.add_argument("--iterations", type=int, default=10000)
    r.add_argument("--workers", type=int, default=6)
    r.add_argument("--run", action="store_true")
    b = sub.add_parser("bench-plan")
    b.add_argument("--header", type=Path, required=True)
    b.add_argument("--workers", type=int, default=6)
    b.add_argument("--profile", default="")
    args = ap.parse_args(argv)
    if args.cmd == "bench":
        exe = bench_binary(args.header, args.namespace)
        print(json.dumps({"binary": str(exe), "iterations": args.iterations, "workers": args.workers,
                          "run": "pass --run on the host, with recorded feature rows on stdin" if not args.run else "running"}))
        if args.run:
            import subprocess  # noqa: PLC0415
            import sys  # noqa: PLC0415
            return subprocess.run([str(exe), str(args.iterations)], stdin=sys.stdin).returncode
        return 0
    if args.cmd == "bench-plan":
        print(json.dumps(bench_plan(args.header, args.workers, args.profile), indent=1))
        return 0
    from training.export_weights import load_policy  # noqa: PLC0415

    layout = feature_layout()
    policy = load_policy(args.policy, layout)
    imp = None
    if args.importance:
        raw = dict(np.load(args.importance))
        imp = {h: [raw[f"{h}.{i}"] for i in range(len(getattr(policy, h).W))] for h in precision.HEADS}
    manifest = export(policy, layout, args.profile, OUT / args.name / args.profile, f"{args.name}_{args.profile}",
                      imp, {"policy": str(args.policy), "family": families.record(layout.schema, policy.family)})
    print(json.dumps({k: manifest[k] for k in ("profile", "profile_identity", "weights_digest", "header_sha256")}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
