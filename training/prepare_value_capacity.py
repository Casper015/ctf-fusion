"""Generate ignored matched capacity bot wrappers/configs using the existing exporter and build/screen tooling.

python -m training.prepare_value_capacity --out build/v_capacity_5xl
python bots/p_only/tools/build.py --stats --variants build/v_capacity_5xl/variants.json
python bots/p_only/tools/run_screen.py --config build/v_capacity_5xl/screen_time.json

Preparation and compilation happen before evidence runs. Generated weights, wrappers,
bundles and binaries remain under build/; no production variant is overwritten.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

from fusion.paths import REPO, sha256
from training.export_mixed import export_runs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="build/v_capacity_5xl")
    ap.add_argument("--runs", default="runs/v_capacity_5xl")
    ap.add_argument("--profile", default="profiles/v_capacity_5xl.json")
    a = ap.parse_args(argv)
    out = Path(a.out)
    if not out.resolve().is_relative_to(REPO / "build"):
        raise SystemExit("generated capacity artifacts must stay under build/")
    profile = json.loads(Path(a.profile).read_text(encoding="utf-8"))
    deployment = profile["deployment"]
    names = [*profile["arms"], "Student"]
    for name in names:
        export_runs(out / "sets" / name, policy_tier="xxl", value_run=Path(a.runs) / f"{name}_s1", max_width=16384)
    variants = []
    for work in ("time", "work"):
        for name in ("Off", *names):
            identity = f"cap_{name.lower()}_{work}"
            (out / "src").mkdir(parents=True, exist_ok=True)
            source = out / "src" / f"{identity}.cpp"
            carrier = Path(os.path.relpath(REPO / "bots/p_only/bots/c08_ponly_f.hpp", source.resolve().parent)).as_posix()
            model = "XL" if name == "Off" else name
            text = ("// Generated by training.prepare_value_capacity. Do not edit.\n"
                    "#define PONLY_POLICY_FAMILY 2\n#define PONLY_VALUE_FAMILY 3\n"
                    f"#define MOD_FUSION_V {int(name != 'Off')}\n"
                    f"#define PONLY_V_MAX_CALLS {deployment['max_calls']}\n"
                    f"#define PONLY_V_DEADLINE_MS {deployment['deadline_ms']}\n"
                    + ("#define PONLY_FIXED_SAMPLES 16\n" if work == "work" else "")
                    + f'#include "../sets/{model}/registry.hpp"\n'
                    + f'#include "{carrier}"\n')
            source.write_bytes(text.encode())
            variants.append({"name": identity, "carrier": "C08", "source": source.as_posix(),
                             "models": (out / "sets" / model).as_posix(), "value_on": name != "Off",
                             "policy_family": "p2", "value_family": "v3", "fixed_samples": 16 if work == "work" else 0})
        arms = [f"cap_{n.lower()}_{work}" for n in ("Off", *names)]
        screen = {"seed": deployment["exploratory_seed"], "teams": deployment["teams"], "maps_per_count": deployment["maps_per_count"],
                  "workers": deployment["workers"], "first_ms": 2000, "turn_ms": 50, "keep_matches": True,
                  "reference": json.loads((REPO / "bots/p_only/profiles/screen_v3xl_matched.json").read_text())["reference"],
                  "arms": arms, "aa": [f"cap_{n.lower()}_{work}" for n in deployment["aa"]],
                  "comparisons": [[arm, arms[0]] for arm in arms[1:]] + [[arms[3], arms[1]], [arms[4], arms[1]]],
                  "work_dir": f"data/v_capacity_5xl/screen_{work}", "report_dir": (out / f"screen_{work}_analysis").as_posix(),
                  "variants": (out / "variants.json").as_posix(),
                  "note": "Exploratory paired fixture seed across time/work diagnostics; not confirmation. Fixed samples may truncate: inspect counters."}
        (out / f"screen_{work}.json").write_text(json.dumps(screen, indent=1) + "\n", encoding="utf-8")
    (out / "variants.json").write_text(json.dumps({"variants": variants}, indent=1) + "\n", encoding="utf-8")
    record = {"profile_sha256": sha256(Path(a.profile)), "generated_sources": {v["source"]: sha256(REPO / v["source"]) for v in variants},
              "policy_manifest_sha256": sha256(REPO / "inference/models_xxl/MANIFEST.json"),
              "carrier_sha256": sha256(REPO / "bots/p_only/bots/c08_ponly_f.hpp")}
    (out / "preparation.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
    print(f"[capacity] {len(variants)} matched variants prepared under {out}; build before taking evidence locks")


if __name__ == "__main__":
    main()
